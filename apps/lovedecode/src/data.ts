export type Scores = Record<Domain, number>; // 영역 평균 0~3

export function computeScores(answers: Record<string, number>): Scores {
  const sum: Partial<Record<Domain, number>> = {};
  const cnt: Partial<Record<Domain, number>> = {};
  for (const q of QUESTIONS) {
    const v = answers[q.id] ?? 0;
    sum[q.d] = (sum[q.d] ?? 0) + v;
    cnt[q.d] = (cnt[q.d] ?? 0) + 1;
  }
  const out = {} as Scores;
  (Object.keys(DOMAIN_LABEL) as Domain[]).forEach((d) => {
    out[d] = cnt[d] ? (sum[d] ?? 0) / (cnt[d] as number) : 0;
  });
  return out;
}

export function judge(answers: Record<string, number>, s: Scores): ResultKey {
  // 안전: 폭력은 한 번이라도, 나머지는 '자주' 이상이면 안전 우선
  if ((answers.s4 ?? 0) >= 1 || (answers.s3 ?? 0) >= 1) return 'safety';
  if ((answers.s1 ?? 0) >= 2 || (answers.s2 ?? 0) >= 2) return 'safety';

  // 문제 지수: 경멸에 가중치
  const risk =
    (s.respect * 1.5 + s.conflict + s.trust * 1.2 + s.warmth + s.balance + s.future) / 6.7;

  if (risk >= 1.8) {
    // 문제가 크지만 좋아하는 마음이 강하고 경멸이 심하지 않으면 갈림길
    if (s.bond >= 2 && s.respect < 1.5) return 'crossroad';
    return 'leave';
  }
  if (risk >= 1.25) {
    if (s.bond < 1 && s.inertia >= 2) return 'leave';
    return 'crossroad';
  }
  if (risk >= 0.7) {
    // 존중·신뢰가 비교적 괜찮고 거리·소진이 주된 문제면 지친 관계
    if (s.respect < 1.2 && s.trust < 1.4) return 'tired';
    return 'crossroad';
  }
  return 'healthy';
}

/** 영역별 '건강도' 0~100 (높을수록 좋음) */
export function health(v: number) {
  return Math.round((1 - v / 3) * 100);
}

/** 가장 약한 영역 2개 */
export function weakest(s: Scores): (keyof typeof ADVICE)[] {
  return (HEALTH_DOMAINS as (keyof typeof ADVICE)[])
    .filter((d) => s[d] >= 0.67)
    .sort((a, b) => s[b] - s[a])
    .slice(0, 2);
}

